import threading
from urllib.robotparser import RobotFileParser

PERSONAL_DATA_URL_PATTERNS = [
    "/author/", "/profile/", "/user/", "/member/", "/comments/",
    "/forum/", "/community/", "linkedin.com/in/", "facebook.com/",
    "twitter.com/", "x.com/", "instagram.com/",
]

_robots_cache = {}
_robots_lock = threading.Lock()


def is_scraping_allowed(url):
    """
    Checks robots.txt (cached per domain, thread-safe) and
    filters out personal-data-looking URLs. Fetches robots.txt
    with a short explicit timeout rather than RobotFileParser's
    own .read() (which has no timeout and can hang on a slow site).
    """
    lowered = url.lower()
    if any(p in lowered for p in PERSONAL_DATA_URL_PATTERNS):
        return False
    try:
        parsed = urlparse(url)
        base = f"{parsed.scheme}://{parsed.netloc}"
        with _robots_lock:
            cached = _robots_cache.get(base, "MISS")
        if cached == "MISS":
            rp = RobotFileParser()
            try:
                resp = requests.get(f"{base}/robots.txt", headers=HEADERS, timeout=5)
                rp.parse(resp.text.splitlines())
            except Exception:
                rp = None
            with _robots_lock:
                _robots_cache[base] = rp
            cached = rp
        return True if cached is None else cached.can_fetch(HEADERS["User-Agent"], url)
    except Exception:
        return False


