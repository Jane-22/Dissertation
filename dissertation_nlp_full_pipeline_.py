# ------------------------------------------------------------
# Matching: check that a keyword's core words are all present in
# the text (any order, any position, simple plurals allowed)
# instead of requiring the exact contiguous phrase. An exact
# match rarely fires on real prose - e.g. "AI demand forecasting"
# vs. how people actually write "AI-driven demand forecasting".
# ------------------------------------------------------------
_STOPWORDS = {"in", "for", "the", "of", "and", "to", "a", "an", "on", "with"}


def _term_tokens(term):
    normalized = term.lower().replace("-", " ")
    tokens = re.findall(r"[a-z0-9][a-z0-9\.]*", normalized)
    return [t for t in tokens if t not in _STOPWORDS]


def _term_present(text_lower, term):
    return all(
        re.search(r"\b" + re.escape(tok) + r"s?\b", text_lower)
        for tok in _term_tokens(term)
    )


def count_keyword_mentions(text, keywords):
    text_lower = text.lower()
    return sum(1 for kw in keywords if _term_present(text_lower, kw))


def has_keywords(text, keywords):
    text_lower = text.lower()
    return any(_term_present(text_lower, kw) for kw in keywords)

