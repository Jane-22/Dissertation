"""## 5. Stage 2 - Reliability analysis (Cronbach's alpha)

Threshold: alpha >= 0.70 (Peterson, 1994). If a construct falls below this, the
item with the lowest item-total correlation is identified and removed, and
alpha is recalculated.

"""

def cronbach_with_diagnostics(data, cols, construct_name, threshold=0.70):
    working_cols = list(cols)
    subset = data[working_cols].dropna()

    alpha, ci = pg.cronbach_alpha(data=subset)
    print(f"\n{construct_name} - initial alpha (k={len(working_cols)} items, n={len(subset)}): "
          f"{alpha:.3f}  95% CI [{ci[0]:.3f}, {ci[1]:.3f}]")

    removed_item = None
    if alpha < threshold:
        print(f"  Below the {threshold} threshold - examining item-total correlations...")
        item_total_corrs = {}
        for col in working_cols:
            rest = [c for c in working_cols if c != col]
            item_total_corrs[col] = subset[col].corr(subset[rest].mean(axis=1))

        for col, corr in sorted(item_total_corrs.items(), key=lambda x: x[1]):
            print(f"    Item-total r = {corr:.3f}  ({col[:60]!r})")

        removed_item = min(item_total_corrs, key=item_total_corrs.get)
        working_cols = [c for c in working_cols if c != removed_item]
        subset2 = data[working_cols].dropna()
        alpha2, ci2 = pg.cronbach_alpha(data=subset2)
        print(f"\n  Removed weakest item ({removed_item[:60]!r}, item-total r="
              f"{item_total_corrs[removed_item]:.3f}).")
        print(f"  Recalculated alpha (k={len(working_cols)} items, n={len(subset2)}): "
              f"{alpha2:.3f}  95% CI [{ci2[0]:.3f}, {ci2[1]:.3f}]")
        alpha, ci = alpha2, ci2
    else:
        print(f"  Meets the {threshold} threshold - no items removed.")

    return {
        "construct": construct_name, "final_items": working_cols,
        "alpha": alpha, "ci_low": ci[0], "ci_high": ci[1], "removed_item": removed_item,
    }


