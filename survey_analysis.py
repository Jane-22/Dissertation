"""## 7. Stage 4 - Hierarchical Multiple Regression (H1 & H3)

This stage implements a single hierarchical multiple regression model with three sequential blocks to test both Hypothesis 1 (H1) and Hypothesis 3 (H3), as per the specified methodology.

Dependent variable: Supply Chain Resilience composite.

-   **Block 1**: Control variables (job level, geographic region, organisation size), dummy-coded, are entered.
    *   *Purpose*: To establish how much variance in Supply Chain Resilience they account for on their own.

-   **Block 2**: AI Adoption composite is added to the model.
    *   *Purpose*: To isolate its relationship with Supply Chain Resilience after accounting for the control variables.
    *   **H1 test**: The standardised Beta and associated p-value for AI Adoption at this stage provide the primary test of H1. A positive and statistically significant Beta supports H1.

-   **Block 3**: Industry 5.0 Readiness composite is added to the model, after AI Adoption is already present.
    *   *Purpose*: To determine the additional variance explained by Industry 5.0 Readiness.
    *   **H3 test**: The R-squared change between Block 2 and Block 3 indicates how much additional variance in Supply Chain Resilience Industry 5.0 Readiness explains beyond AI Adoption alone. H3 is supported where this R-squared change is statistically significant, and the standardised Beta and p-value for Industry 5.0 Readiness in Block 3 are positive and significant. This provides direct evidence that Industry 5.0 Readiness explains additional variance in Supply Chain Resilience after AI Adoption has been included in the model.
"""

reg_df = df.dropna(subset=["SC_Resilience", "AI_Adoption", "Industry5_Readiness",
                            COL_JOB_LEVEL, COL_REGION, COL_ORG_SIZE]).copy()
print(f"Regression sample (complete cases on all model variables): {len(reg_df)}")

control_dummies = pd.get_dummies(
    reg_df[[COL_JOB_LEVEL, COL_REGION, COL_ORG_SIZE]],
    prefix=["JobLevel", "Region", "OrgSize"], drop_first=True
).astype(float)

control_col_names = list(control_dummies.columns)
print(f"\nControl variables (dummy-coded, reference category dropped): {control_col_names}")

def zscore(s):
    return (s - s.mean()) / s.std()

model_df = pd.concat([
    reg_df[["SC_Resilience", "AI_Adoption", "Industry5_Readiness"]].reset_index(drop=True),
    control_dummies.reset_index(drop=True)
], axis=1)

z_df = model_df.copy()
for col in ["SC_Resilience", "AI_Adoption", "Industry5_Readiness"] + control_col_names:
    if z_df[col].std() > 0:
        z_df[col] = zscore(z_df[col])

# Dependent variable
y = z_df["SC_Resilience"]

# --- Block 1: Controls only ---
X1_block = sm.add_constant(z_df[control_col_names])
model1 = sm.OLS(y, X1_block).fit()

# --- Block 2: Controls + AI Adoption ---
X2_block = sm.add_constant(z_df[control_col_names + ["AI_Adoption"]])
model2 = sm.OLS(y, X2_block).fit()

# --- Block 3: Controls + AI Adoption + Industry 5.0 Readiness ---
X3_block = sm.add_constant(z_df[control_col_names + ["AI_Adoption", "Industry5_Readiness"]])
model3 = sm.OLS(y, X3_block).fit()

# --- Calculate R^2 change for Block 2 from Block 1 ---
r2_change_2v1 = model2.rsquared - model1.rsquared
f_num_2v1 = (model2.rsquared - model1.rsquared) / (X2_block.shape[1] - X1_block.shape[1])
f_den_2v1 = (1 - model2.rsquared) / (len(z_df) - X2_block.shape[1] - 1)
f_change_2v1 = f_num_2v1 / f_den_2v1
df1_2v1 = X2_block.shape[1] - X1_block.shape[1]
df2_2v1 = len(z_df) - X2_block.shape[1] - 1
f_change_2v1_p = 1 - stats.f.cdf(f_change_2v1, df1_2v1, df2_2v1)

# --- Calculate R^2 change for Block 3 from Block 2 ---
r2_change_3v2 = model3.rsquared - model2.rsquared
f_num_3v2 = (model3.rsquared - model2.rsquared) / (X3_block.shape[1] - X2_block.shape[1])
f_den_3v2 = (1 - model3.rsquared) / (len(z_df) - X3_block.shape[1] - 1)
f_change_3v2 = f_num_3v2 / f_den_3v2
df1_3v2 = X3_block.shape[1] - X2_block.shape[1]
df2_3v2 = len(z_df) - X3_block.shape[1] - 1
f_change_3v2_p = 1 - stats.f.cdf(f_change_3v2, df1_3v2, df2_3v2)

print("=" * 65)
print("HIERARCHICAL MULTIPLE REGRESSION - DV: Supply Chain Resilience")
print("=" * 65)

print(f"\nBlock 1 (controls only): R^2 = {model1.rsquared:.3f}")
print(f"Block 2 (+ AI Adoption): R^2 = {model2.rsquared:.3f} (Delta R^2 from Block 1 = {r2_change_2v1:.3f})")
print(f"  F change({df1_2v1},{df2_2v1}) = {f_change_2v1:.3f}, p = {f_change_2v1_p:.4f}")
print(f"Block 3 (+ Industry 5.0 Readiness): R^2 = {model3.rsquared:.3f} (Delta R^2 from Block 2 = {r2_change_3v2:.3f})")
print(f"  F change({df1_3v2},{df2_3v2}) = {f_change_3v2:.3f}, p = {f_change_3v2_p:.4f}")

# --- H1 Interpretation ---
print("\n" + "=" * 65)
print("H1 INTERPRETATION (from Block 2, AI Adoption's Beta)")
print("=" * 65)
ai_beta_h1 = model2.params["AI_Adoption"]
ai_p_h1 = model2.pvalues["AI_Adoption"]
h1_supported = (ai_beta_h1 > 0) and (ai_p_h1 < 0.05)
print('H1 - "AI Adoption is positively and significantly related to Supply Chain Resilience after controlling for job level, geographic region, and organisation size."')
print(f"  AI Adoption (Block 2): Beta = {ai_beta_h1:.3f}, p = {ai_p_h1:.4f}")
print(f"  H1: {'SUPPORTED' if h1_supported else 'NOT SUPPORTED'}")

# --- H3 Interpretation ---
print("\n" + "=" * 65)
print("H3 INTERPRETATION (from Block 3, Industry 5.0 Readiness Beta and R^2 Change)")
print("=" * 65)
i5_beta_h3 = model3.params["Industry5_Readiness"]
i5_p_h3 = model3.pvalues["Industry5_Readiness"]
