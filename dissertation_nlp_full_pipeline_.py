"""## 13. Co-occurrence analysis

Per the methodology: tests whether AI, supply chain resilience, and
Industry 5.0 terms appear together significantly more than chance, at four
levels of strictness (document, sentence, paragraph, 3-sentence window).
"""

def cooccurrence_stats(df, v1, v2, label, level_name, unit_col_name):
    both = (df[v1] & df[v2]).sum()
    either = (df[v1] | df[v2]).sum()
    jaccard = both / either if either > 0 else 0
    phi, p = stats.pearsonr(df[v1].astype(int), df[v2].astype(int))
    sig = "***" if p < 0.001 else "**" if p < 0.01 else "*" if p < 0.05 else "n.s."
    print(f"  {label:<45} co-occur in {both} {unit_col_name}, "
          f"Jaccard={jaccard:.3f}, phi={phi:.3f} {sig}")
    return {
        "Comparison": label, "Level": level_name,
        f"co_occurring_{unit_col_name}": int(both), "jaccard": round(jaccard, 3),
        "phi_coefficient": round(phi, 3), "p_value": round(p, 3), "Significance": sig
    }


