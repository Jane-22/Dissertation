nlp = spacy.load("en_core_web_sm", disable=["ner", "parser"])
nlp.max_length = 2_000_000

def preprocess_spacy(text):
    text = text.lower()
    text = re.sub(r"[^a-z\s]", " ", text)   # strip punctuation/special chars, keep letters
    doc = nlp(text)
    lemmas = [
        tok.lemma_ for tok in doc
        if not tok.is_stop and not tok.is_space and len(tok.lemma_) >= 3
    ]
    return " ".join(lemmas)

