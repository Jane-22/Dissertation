"""## 12. Sentiment analysis (RoBERTa)

Per the methodology: each document classified positive/neutral/negative using
a pre-trained RoBERTa transformer. Documents are chunked to the model's token
limit and chunk-level probabilities averaged, since reports often exceed 512
tokens. Produces evidence for **H1** (positive sentiment in AI+resilience
co-mentions) and **H3** (sentiment difference between `primary` and
`comparative` document groups).
"""

from transformers import AutoTokenizer, AutoModelForSequenceClassification
import torch
import torch.nn.functional as F

SENTIMENT_MODEL = "cardiffnlp/twitter-roberta-base-sentiment-latest"
sent_tokenizer = AutoTokenizer.from_pretrained(SENTIMENT_MODEL)
sent_model = AutoModelForSequenceClassification.from_pretrained(SENTIMENT_MODEL)
sent_model.eval()
SENT_LABELS = ["negative", "neutral", "positive"]  # this model's label order


def sentiment_for_text(text, max_chunk_words=350):
    """
    Chunks text to fit the model's context window, classifies EACH chunk
    independently, and takes the MAJORITY VOTE of per-chunk labels (not the
    average of softmax probabilities).

    Why majority vote instead of averaging: averaging probabilities across
    chunks systematically dilutes localized negative language. A report might
    have one paragraph on disruption/risk (negative) surrounded by neutral
    operational description - averaging softmax scores across 8 chunks pulls
    that signal toward neutral before argmax is even applied, so genuinely
    negative sections of text tend to average out to a neutral document. A
    majority vote preserves whichever sentiment is most COMMON across chunks,
    which is a more standard and defensible way to aggregate.

    Also returns:
      - max_negative_prob: the single HIGHEST negative-class probability seen
        across any chunk, and whether that chunk's argmax was actually
        "negative" (chunk_negative_dominant). This is a supplementary signal -
        even if the document's majority-vote label isn't negative, this shows
        whether meaningfully negative/risk language appears anywhere in it,
        which matters for interpreting a "zero negative documents" result.
    """
    words = text.split()
    if not words:
        return "neutral", 1 / 3, 1 / 3, 1 / 3, 0.0, False

    chunks = [" ".join(words[i:i + max_chunk_words])
              for i in range(0, len(words), max_chunk_words)]
    chunks = chunks[:8]  # cap runtime

    chunk_labels = []
    chunk_probs = []
    with torch.no_grad():
        for chunk in chunks:
            inputs = sent_tokenizer(chunk, return_tensors="pt", truncation=True, max_length=512)
            logits = sent_model(**inputs).logits[0]
            probs = F.softmax(logits, dim=0)
            chunk_labels.append(SENT_LABELS[int(probs.argmax())])
            chunk_probs.append(probs.tolist())

    # Majority vote across chunks (ties broken by mean probability)
    from collections import Counter
    vote_counts = Counter(chunk_labels)
    top_count = max(vote_counts.values())
    tied_labels = [l for l, c in vote_counts.items() if c == top_count]

    mean_probs = torch.tensor(chunk_probs).mean(dim=0).tolist()
    if len(tied_labels) == 1:
        final_label = tied_labels[0]
    else:
        final_label = SENT_LABELS[int(torch.tensor(mean_probs).argmax())]

    # Supplementary "critical language" signal
    neg_probs_per_chunk = [p[0] for p in chunk_probs]
    max_negative_prob = max(neg_probs_per_chunk)
    chunk_negative_dominant = any(l == "negative" for l in chunk_labels)

    return final_label, mean_probs[0], mean_probs[1], mean_probs[2], max_negative_prob, chunk_negative_dominant

